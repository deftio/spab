#!/usr/bin/env node
/*
 * benchmark.js — the comprehensive spab benchmark surface.
 *
 * This is RESEARCH testing, and the distinction from CI testing is the point:
 *
 *   tests/          proves the implementation WORKS. Assertions are binary and
 *                   must never regress: round-trips hold, nothing throws, unmarked
 *                   text yields nothing, a damaged mark never returns a WRONG
 *                   payload. Percentages are reported there, never asserted.
 *
 *   r_and_d/        measures how WELL it works, and where it does not. Numbers here
 *                   move whenever the codec moves, and that is what they are for.
 *                   Nothing in this file gates anything.
 *
 * Review dev/spab_0.5_review.md section 15 argues that "one robustness score" is the
 * wrong output and a benchmark should report an operating surface instead. So this
 * emits several tables rather than a headline figure:
 *
 *   1. capacity      what a document can hold, before robustness enters
 *   2. operating     payload x cover -> redundancy achieved, and recovery
 *   3. channels      recovery per real-world corruption model, per carrier set
 *   4. severity      recovery vs corruption intensity, the degradation curve
 *   5. safety        false positives and wrong payloads (must be zero)
 *   6. cost          encode/decode time and distortion
 *
 * Deterministic: fixed samples, fixed payloads, seeded corruption. Same input gives
 * the same table.
 *
 * Thorough by design and slow by consequence: it runs the full corpus against every
 * payload profile, every carrier set, both ECC modes, four cover lengths and all 27
 * channel models. There is no fast mode — this is run periodically, not in CI, and a
 * benchmark that samples its own matrix reports a number nobody can reproduce.
 * Expect minutes.
 *
 *   node r_and_d/benchmark.js                 print the tables
 *   node r_and_d/benchmark.js --md FILE       also write markdown
 */
'use strict';

const SPAB = require('../src/js/spab.js');
const { SAMPLES } = require('./samples.js');
const { PROFILES } = require('./payloads.js');
const { MODELS, makeRng } = require('./corruptions.js');
const { describe, completeness } = require('./attacks.js');
const fs = require('fs');
const path = require('path');

const ARGV = process.argv.slice(2);
const MD_AT = ARGV.indexOf('--md');
const MD_PATH = MD_AT >= 0 ? ARGV[MD_AT + 1] : null;

const CARRIERS = [
  { name: 'default', note: 'ws + apos + hyphen', params: {} },
  { name: 'ws-only', note: 'whitespace alone', params: { classes: ['ws'] } },
  { name: 'punct', note: 'NFKC-durable only', params: { classes: ['apos', 'hyphen'] } },
  { name: 'wsdense', note: '8 variants, 3 bits/site', params: { classes: ['wsdense'] } },
  { name: 'zero-width', note: 'inserts, not length-preserving', params: { classes: ['zwsp'] } }
];
const ECCS = ['repetition', 'rlnc'];
const payloads = PROFILES;
const samples = SAMPLES;

// A model with no catalogue entry would appear as an unexplained row. Fail instead.
const gaps = completeness();
if (gaps.missing.length) {
  console.error('undocumented channel models: ' + gaps.missing.join(', ') +
    '\n  add them to r_and_d/attacks.js before publishing a table');
  process.exit(1);
}

const out = [];
function say(s) { console.log(s); out.push(s); }
function table(headers, rows, aligns) {
  const w = headers.map((h, i) => Math.max(h.length, ...rows.map(r => String(r[i]).length)));
  const pad = (s, i) => (aligns && aligns[i] === 'r') ? String(s).padStart(w[i]) : String(s).padEnd(w[i]);
  say('| ' + headers.map(pad).join(' | ') + ' |');
  say('|' + w.map((n, i) => (aligns && aligns[i] === 'r' ? '-'.repeat(n + 1) + ':' : '-'.repeat(n + 2))).join('|') + '|');
  rows.forEach(r => say('| ' + r.map(pad).join(' | ') + ' |'));
  say('');
}
const pct = (a, b) => b ? Math.round(100 * a / b) + '%' : '-';

function encodeSafe(cover, text, params) {
  try { return SPAB.encode(cover, text, params); } catch (e) { return null; }
}
function decodeSafe(text, params) {
  try { return SPAB.decode(text, params); } catch (e) { return { message: null, metadata: { status: 'threw' } }; }
}
// A round trip that is known to work before damage is applied. Anything that cannot
// encode is excluded from robustness tables rather than counted as a failure — it is
// a capacity fact and table 1 already reports it.
function baseline(sample, payload, carrier, ecc) {
  const params = Object.assign({ ecc: ecc }, carrier.params);
  const e = encodeSafe(sample.text, payload.text, params);
  if (!e) return null;
  if (decodeSafe(e.text, params).message !== payload.text) return null;
  return { e: e, params: params };
}

say('# spab benchmark');
say('');
say('spab ' + SPAB.VERSION + ', wire format v' + SPAB.algorithm.frame.version +
  '. Generated by `node r_and_d/benchmark.js`.');
say('');
say('Research measurement, not a gate. `tests/` proves the implementation works;');
say('this measures how well, and where it does not. Every number moves when the');
say('codec moves — that is what they are for.');
say('');

// --------------------------------------------------------------- 0. the models
say('## 0. What is being tested');
say('');
say('Every channel model, what it does, and the real situation it stands in for.');
say('A result is only readable if you know what produced it, so this table comes');
say('before any number.');
say('');
say('`control` must always survive — a failure there is a bug, not a measurement.');
say('`channel` is ordinary document handling. `attack` is someone deliberately');
say('removing a mark, which spab explicitly does not claim to resist.');
say('');
{
  const kindOrder = { control: 0, channel: 1, attack: 2 };
  const rows = Object.keys(MODELS)
    .map(describe)
    .sort((a, b) => kindOrder[a.kind] - kindOrder[b.kind] || a.name.localeCompare(b.name))
    .map(d => [d.name, d.kind, d.what, d.why, d.hits, d.intensities.join(' / ')]);
  table(['model', 'kind', 'what it does', 'what it stands in for', 'damages', 'intensities'], rows);
}

// ---------------------------------------------------------------- 1. capacity
say('## 1. Capacity');
say('');
say('What a document can hold before robustness enters. `bytes/copy` is the largest');
say('incompressible payload that fits once, so it already nets off packet overhead.');
say('');
{
  const rows = samples.map(s => {
    const chars = s.text.length;
    const words = s.text.split(/\s+/).filter(Boolean).length;
    const cells = CARRIERS.slice(0, 4).map(c => {
      const e = encodeSafe(s.text, 'x', c.params);
      return e ? e.metadata.capacityBits : 0;
    });
    // largest payload that still round-trips once, by bisection on an incompressible string
    let lo = 0, hi = 400;
    const mk = n => Array.from({ length: n }, (_, i) => String.fromCharCode(33 + ((i * 37 + 11) % 90))).join('');
    while (lo < hi) {
      const mid = Math.ceil((lo + hi) / 2);
      const e = encodeSafe(s.text, mk(mid), { compress: false });
      const ok = e && decodeSafe(e.text, {}).message === mk(mid);
      if (ok) lo = mid; else hi = mid - 1;
    }
    return [s.name, chars, words, cells[0], cells[1], cells[2], cells[3], lo];
  });
  table(['sample', 'chars', 'words', 'default', 'ws-only', 'punct', 'wsdense', 'bytes/copy'],
    rows, [null, 'r', 'r', 'r', 'r', 'r', 'r', 'r']);
  say('Capacity columns are bits at one copy for the STRONGEST channel in that set,');
  say('not a sum. Carrier classes are independent parallel channels and each carries');
  say('the whole payload, so what decides whether a payload fits is the largest single');
  say('channel — which is why `default` (ws + apos + hyphen) matches `ws-only`. The');
  say('extra classes buy failure diversity, not room.');
  say('');
  say('`punct` is small on purpose: it is the channel that survives NFKC, and prose');
  say('simply does not contain many apostrophes and hyphens.');
  say('');
}

// ------------------------------------------------------------- 2. operating point
say('## 2. Operating point');
say('');
say('Redundancy achieved for each payload against each cover, with the default');
say('carriers. Redundancy is the variable that moves recovery — see table 4.');
say('');
{
  const rows = samples.map(s => {
    const cells = payloads.map(p => {
      const e = encodeSafe(s.text, p.text, {});
      if (!e) return '-';
      const ok = decodeSafe(e.text, {}).message === p.text;
      return ok ? String(e.metadata.reps) + 'x' : 'no fit';
    });
    return [s.name].concat(cells);
  });
  table(['sample'].concat(payloads.map(p => p.name + ' (' + p.bytes + 'B)')), rows,
    [null].concat(payloads.map(() => 'r')));
  say('`no fit` is reported honestly by `encode` in `metadata.issues`; it is never a');
  say('silent failure.');
  say('');
}

// ------------------------------------------------------------------- 3. channels
say('## 3. Real-world channels, by redundancy');
say('');
say('Recovery per corruption model at its median intensity, **split by how many');
say('copies of the payload fit**. Redundancy is the dominant variable and a single');
say('averaged column hides it: the same model reads 0% on a passage that fits one');
say('copy and 100% on one that fits eight. Quoting the average of those would');
say('describe neither.');
say('');
say('Each sample is therefore measured at several lengths (1x, 3x, 8x, 20x) and the');
say('results are grouped by the redundancy actually achieved.');
say('');
const BANDS = [
  { name: '1 copy', test: r => r <= 1 },
  { name: '2-4', test: r => r >= 2 && r <= 4 },
  { name: '5-8', test: r => r >= 5 && r <= 8 },
  { name: '9+', test: r => r >= 9 }
];
const SCALES = [1, 3, 8, 20];
// Only carrier sets that can actually hold a payload in this corpus. `punct` alone
// is 0-13 bits on these samples against a 32-bit minimum payload, so it encodes
// nothing and would show an empty column that reads like a failure rather than a
// capacity fact. Table 1 already reports why.
const ROBUST_CARRIERS = CARRIERS.filter(c => c.name !== 'punct');

function sweep(modelName, intensity, carrier) {
  const tally = BANDS.map(() => ({ ok: 0, tot: 0 }));
  const spec = MODELS[modelName];
  for (const s of samples) for (const scale of SCALES) {
    const cover = scale === 1 ? s.text : s.text.repeat(scale);
    for (const p of payloads) for (const ecc of ECCS) {
      const params = Object.assign({ ecc: ecc }, carrier.params);
      const e = encodeSafe(cover, p.text, params);
      if (!e) continue;
      if (decodeSafe(e.text, params).message !== p.text) continue;
      const band = BANDS.findIndex(b => b.test(e.metadata.reps || 1));
      if (band < 0) continue;
      tally[band].tot++;
      if (decodeSafe(spec.fn(e.text, intensity, makeRng(0xBEEF)), params).message === p.text) tally[band].ok++;
    }
  }
  return tally;
}

{
  const rows = [];
  for (const m of Object.keys(MODELS)) {
    const spec = MODELS[m];
    const intensity = spec.intensities[Math.floor(spec.intensities.length / 2)];
    const t = sweep(m, intensity, CARRIERS[0]);
    rows.push([m, String(intensity)].concat(t.map(x => x.tot ? pct(x.ok, x.tot) : '-')));
  }
  const score = r => r.slice(2).map(v => v === '-' ? -1 : parseInt(v)).reduce((a, b) => a + b, 0);
  rows.sort((a, b) => score(b) - score(a) || a[0].localeCompare(b[0]));
  say('### Default carriers (ws + apos + hyphen)');
  say('');
  table(['model', 'intensity'].concat(BANDS.map(b => b.name)), rows,
    [null, 'r'].concat(BANDS.map(() => 'r')));
  say('Read a row across, not down: a model at 0% / 100% is not unreliable, it is a');
  say('model that needs redundancy and gets it once the passage is long enough.');
  say('');
}
{
  // The same question asked of each carrier set, collapsed to one number per set so
  // the sets can be compared at all. Cells mix redundancy bands, so use this to
  // compare CARRIERS against each other, not to predict a single document.
  const rows = [];
  for (const m of Object.keys(MODELS)) {
    const spec = MODELS[m];
    const intensity = spec.intensities[Math.floor(spec.intensities.length / 2)];
    const cells = ROBUST_CARRIERS.map(c => {
      const t = sweep(m, intensity, c);
      const ok = t.reduce((a, x) => a + x.ok, 0), tot = t.reduce((a, x) => a + x.tot, 0);
      return tot ? pct(ok, tot) : '-';
    });
    rows.push([m].concat(cells));
  }
  rows.sort((a, b) => a[0].localeCompare(b[0]));
  say('### By carrier set (all redundancy bands pooled)');
  say('');
  table(['model'].concat(ROBUST_CARRIERS.map(c => c.name)), rows,
    [null].concat(ROBUST_CARRIERS.map(() => 'r')));
  say('`zero-width` wins most rows because it inserts rather than substitutes, so it');
  say('reaches high copy counts on any passage — and loses every row where invisible');
  say('characters are stripped. That is the trade, visible in one table.');
  say('');
}

// ------------------------------------------------------------------- 4. severity
say('## 4. Degradation curve');
say('');
say('Recovery against corruption intensity, default carriers, pooled across');
say('redundancy. A codec that cliff-edges is worse than one that degrades, even at');
say('the same average.');
say('');
{
  const scaled = Object.keys(MODELS).filter(m => MODELS[m].intensities.length >= 3);
  const rows = [];
  for (const m of scaled) {
    const spec = MODELS[m];
    const cells = spec.intensities.map(intensity => {
      const t = sweep(m, intensity, CARRIERS[0]);
      const ok = t.reduce((a, x) => a + x.ok, 0), tot = t.reduce((a, x) => a + x.tot, 0);
      return tot ? pct(ok, tot) : '-';
    });
    rows.push([m, spec.intensities.join(' / '), spec.note.slice(0, 34)]
      .concat(cells, new Array(Math.max(0, 4 - cells.length)).fill('')));
  }
  table(['model', 'intensities', 'meaning', 'lo', '', '', 'hi'], rows,
    [null, null, null, 'r', 'r', 'r', 'r']);
}

// --------------------------------------------------------------------- 5. safety
say('## 5. Safety');
say('');
say('The invariant the project actually promises. A mark may be lost; it must never');
say('come back as something else, and unmarked text must never yield a payload.');
say('');
{
  let fp = 0, fpTot = 0, wrong = 0, lost = 0, rec = 0;
  for (const s of samples) for (const c of CARRIERS) for (const ecc of ECCS) {
    const params = Object.assign({ ecc: ecc }, c.params);
    fpTot++;
    if (decodeSafe(s.text, params).message !== null) fp++;
  }
  for (const s of samples) for (const p of payloads) for (const c of CARRIERS) {
    const b = baseline(s, p, c, 'repetition');
    if (!b) continue;
    for (const m of Object.keys(MODELS)) {
      const spec = MODELS[m];
      const got = decodeSafe(spec.fn(b.e.text, spec.intensities[spec.intensities.length - 1], makeRng(7)), b.params).message;
      if (got === p.text) rec++; else if (got === null) lost++; else wrong++;
    }
  }
  table(['measurement', 'result', 'requirement'], [
    ['payload reported from unmarked text', fp + ' / ' + fpTot, 'must be 0'],
    ['wrong payload from a damaged mark', wrong + ' / ' + (rec + lost + wrong), 'must be 0'],
    ['recovered at worst-case intensity', rec + ' (' + pct(rec, rec + lost + wrong) + ')', 'reported, not required'],
    ['lost at worst-case intensity', lost + ' (' + pct(lost, rec + lost + wrong) + ')', 'reported, not required']
  ], [null, 'r', null]);
  if (fp || wrong) say('**A safety requirement is violated above — this is a bug, not a measurement.**\n');
}

// ----------------------------------------------------------------------- 6. cost
say('## 6. Cost and distortion');
say('');
say('`distortion` is the share of eligible carrier sites the encoder actually');
say('changed — the steganalysis-relevant number, since an untouched site looks like');
say('every other untouched site.');
say('');
{
  const rows = [];
  for (const c of CARRIERS) {
    const s = samples[samples.length - 1], p = payloads[Math.floor(payloads.length / 2)];
    const b = baseline(s, p, c, 'repetition');
    if (!b) { rows.push([c.name, c.note, '-', '-', '-', '-']); continue; }
    const t0 = process.hrtime.bigint();
    for (let i = 0; i < 20; i++) SPAB.encode(s.text, p.text, b.params);
    const t1 = process.hrtime.bigint();
    for (let i = 0; i < 20; i++) SPAB.decode(b.e.text, b.params);
    const t2 = process.hrtime.bigint();
    let changed = 0;
    for (let i = 0; i < Math.min(s.text.length, b.e.text.length); i++) if (s.text[i] !== b.e.text[i]) changed++;
    const sites = SPAB.getSites(s.text, b.params).length;
    const grew = b.e.text.length - s.text.length;
    rows.push([c.name, c.note,
      (Number(t1 - t0) / 20e6).toFixed(2) + 'ms',
      (Number(t2 - t1) / 20e6).toFixed(2) + 'ms',
      sites ? pct(changed, sites) : '-',
      grew === 0 ? 'none' : '+' + grew + ' chars']);
  }
  table(['carriers', 'note', 'encode', 'decode', 'distortion', 'length'], rows,
    [null, null, 'r', 'r', 'r', 'r']);
}

say('---');
say('');
say('Side-by-side comparison against other libraries lives in `comparisons/`, kept');
say('separate because it needs third-party packages and this repo has none.');
say('It is not run in CI.');

if (MD_PATH) {
  fs.mkdirSync(path.dirname(MD_PATH), { recursive: true });
  fs.writeFileSync(MD_PATH, out.join('\n') + '\n');
  console.error('\nwrote ' + MD_PATH);
}
